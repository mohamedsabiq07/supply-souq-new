// Helper to map supplier items to sanitized Customer Offer Items (with 5% selling markup applied to unit prices)
const buildCustomerOfferItems = (offerId: string, supplierQuote: Quotation, markupMultiplier = 1.05) => {
  return supplierQuote.items.map((item, idx) => {
    const isIncluded = item.isQuoted !== false && item.unitPriceAED > 0;
    const customerUnit = isIncluded ? Math.round(item.unitPriceAED * markupMultiplier * 100) / 100 : 0;
    return {
      id: `${offerId}-item-${idx + 1}`,
      customerOfferId: offerId,
      rfqItemId: item.rfqItemId,
      itemNumber: idx + 1,
      description: item.itemDescription,
      offeredBrand: item.offeredBrand,
      specificationCompliance: (!isIncluded
        ? 'Not Quoted'
        : item.isAlternative
        ? 'Alternative'
        : 'Compliant') as any,
      isIncluded,
      isAlternative: item.isAlternative,
      quantity: item.quantity,
      unit: item.unit,
      customerUnitPriceAED: customerUnit,
      customerLineTotalAED: isIncluded ? Math.round(customerUnit * item.quantity * 100) / 100 : 0,
      availability: isIncluded ? 'In Stock (UAE)' : 'Not Quoted',
      leadTimeDays: isIncluded ? supplierQuote.leadTimeDays : 0,
      deviationNote: item.isAlternative ? item.remarks : undefined,
    };
  });
};

